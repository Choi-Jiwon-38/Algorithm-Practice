SELECT
    HISTORY_ID,
    CAR_ID,
    START_DATE,
    END_DATE,
    CASE 
        WHEN DATEDIFF(END_DATE, START_DATE) >= 29 THEN '장기 대여'
        ELSE '단기 대여'
    END AS RENT_TYPE
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
WHERE '2022-09-01' <= START_DATE AND START_DATE < '2022-10-01'
ORDER BY HISTORY_ID DESC