WITH RECURSIVE HOUR_TABLE AS (
    -- base
    SELECT 0 AS HOUR
    
    UNION ALL
    
    -- recursive
    SELECT HOUR + 1
    FROM hour_table
    WHERE HOUR < 23
)


SELECT HT.HOUR AS HOUR, COALESCE(COUNT, 0) AS COUNT
FROM HOUR_TABLE AS HT
    LEFT JOIN (
        SELECT HOUR(DATETIME) AS HOUR, COUNT(*) AS COUNT
        FROM  ANIMAL_OUTS 
        GROUP BY HOUR(DATETIME)
        ORDER BY HOUR(DATETIME)
    ) AS AO
    ON HT.HOUR = AO.HOUR