WITH RECURSIVE HOUR_TABLE AS (
    SELECT 0 AS HOUR
    
    UNION ALL
    
    SELECT HOUR + 1
    FROM HOUR_TABLE
    WHERE HOUR < 23
)

SELECT HT.HOUR AS HOUR, COALESCE(CT.COUNT, 0) AS COUNT
FROM HOUR_TABLE AS HT
    LEFT JOIN (
        SELECT HOUR(DATETIME) AS HOUR, COUNT(*) AS COUNT
        FROM ANIMAL_OUTS
        GROUP BY HOUR(DATETIME)
    ) AS CT
    ON HT.HOUR = CT.HOUR
ORDER BY HOUR